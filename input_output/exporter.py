"""
Unified exporter for serializing TARA ensembles to disk.
"""
import os
import numpy as np
import pandas as pd
from typing import List, Union, Any

from input_output.leapr.core import LeaprFile
from input_output.leapr.workflows import inject_leapr_spectrum
from input_output.ncrystal.core import NCrystalFile
from input_output.base import BaseFormatFile
from core.data.input_pdos import PhononSpectra


def export_ensemble(base_obj: BaseFormatFile, 
                    ensemble: List[PhononSpectra], 
                    output_dir: str, 
                    output_base: str, *, export_full_spectra: bool = False) -> None:
    """
    Serializes an ensemble of phonon spectra to disk using the original format.

    Parameters
    ----------
    base_obj : BaseFormatFile
        The original file object (LeaprFile or NCrystalFile) serving as the metadata template.
    ensemble : list of PhononSpectra
        The list of perturbed spectra generated by TARA.
    output_dir : str
        The destination directory.
    output_base : str
        The prefix for the output filenames.
    export_full_spectra : bool, optional
        Write LEAPR spectra with ND=0 instead of native discrete modes.
    """
    # Create the destination before writing independently named ensemble outputs.
    os.makedirs(output_dir, exist_ok=True)

    for i, spectrum in enumerate(ensemble):
        # 1-based indexing for output files
        filename = f"{output_base}_{i + 1}"
        out_path = os.path.join(output_dir, filename)

        # Utilize the shallow clone to prevent massive deepcopy overhead in loops
        clone = base_obj.shallow_clone()

        if isinstance(clone, LeaprFile):
            _inject_leapr_spectrum(clone, spectrum, export_full_spectra=export_full_spectra)
            clone.write(f"{out_path}.leapr")

        elif isinstance(clone, NCrystalFile):
            _inject_ncrystal_spectrum(clone, spectrum)
            clone.write(f"{out_path}.ncmat")

        else:
            raise TypeError(f"Unsupported export format object: {type(clone)}")


def _inject_leapr_spectrum(
    leapr_obj: LeaprFile, spectrum: PhononSpectra, *, export_full_spectra: bool = False,
) -> None:
    """Compatibility wrapper around the canonical LEAPR spectrum injector.

    Parameters
    ----------
    leapr_obj : LeaprFile
        LEAPR format object to update.
    spectrum : PhononSpectra
        Source phonon spectrum to evaluate or perturb.
    export_full_spectra : bool, optional
        Write LEAPR spectra with ND=0 instead of native discrete modes.
    """
    inject_leapr_spectrum(leapr_obj, spectrum, export_full_spectra=export_full_spectra)


def _inject_ncrystal_spectrum(nc_obj: NCrystalFile, spectrum: PhononSpectra) -> None:
    """Overrides the NCrystal clone with explicit custom grid arrays.

    Parameters
    ----------
    nc_obj : NCrystalFile
        NCMAT format object to update.
    spectrum : PhononSpectra
        Source phonon spectrum to evaluate or perturb.
    """
    # NCrystal can handle arbitrary spacing via CUSTOM tags
    nc_obj.custom_vdosebins = spectrum.energy_grid
    nc_obj.custom_vdos = spectrum.density_values

def export_ensemble_results(ensemble_data: Any, output_path: str) -> None:
    """
    Serializes an EnsemblePhysicsData container into a single hierarchical HDF5 file.
    
    Parameters
    ----------
    ensemble_data : Any
        The pure state container. Typed as Any to prevent upward imports from the analyzer domain.
    output_path : str
        The destination file path (e.g., 'results.h5').
    """
    # Create the destination before writing independently named ensemble outputs.
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    
    with pd.HDFStore(output_path, mode='w') as store:
        for attr_name, attr_value in ensemble_data.__dict__.items():
            if attr_value is None:
                continue
                
            # 1. Store standard 2D DataFrames (e.g., /xs_inelastic)
            if isinstance(attr_value, pd.DataFrame) and not attr_value.empty:
                # Use format='fixed' to natively support float column names
                store.put(attr_name, attr_value, format='fixed')
                
            # 2. Store Multi-Ein Dictionaries (e.g., /scattering_kernel/ein_0_0253)
            elif isinstance(attr_value, dict):
                for ein, df in attr_value.items():
                    if isinstance(df, pd.DataFrame) and not df.empty:
                        # Replace decimals in the energy float to create safe HDF5 keys
                        clean_ein = str(ein).replace('.', '_')
                        hdf5_path = f"{attr_name}/ein_{clean_ein}"
                        store.put(hdf5_path, df, format='fixed')
