"""
Abstract base interfaces for execution runners and data parsers.
"""
from abc import ABC, abstractmethod
from typing import Any, Dict

from core.data.input_pdos import PhononSpectra
from core.data.material_scattering import MaterialScatteringModel
from analyzer.physics.data_models import PhysicsData


class BaseRunner(ABC):
    """
    Abstract interface for executing nuclear data calculations.
    
    A Runner is strictly responsible for setting up the environment, injecting 
    a spectrum or material realization into the backend, executing 
    the calculation, and managing temporary files.
    """

    def prepare_analysis(self, runner_kwargs: dict, parser_kwargs: dict) -> dict:
        """Prepare execution options before evaluating the ensemble.

        Parameters
        ----------
        runner_kwargs : dict
            Explicit options for backend execution.
        parser_kwargs : dict
            Requested observables and extraction settings.

        Returns
        -------
        dict
            Options to pass to each execution, including the reference.
        """
        return runner_kwargs

    @abstractmethod
    def execute(self, sample_index: int, spectrum: PhononSpectra | MaterialScatteringModel,
                **kwargs) -> Any:
        """
        Executes the backend calculation for a single sample.

        Parameters
        ----------
        sample_index : int
            The unique identifier for the sample (used for safe parallel temp files).
        spectrum : PhononSpectra or MaterialScatteringModel
            Spectrum or complete material realization.
        kwargs : dict
            Backend-specific execution flags (e.g., energy grids, temperature).

        Returns
        -------
        Any
            An opaque output object. For NCrystal, this might be a loaded 
            material object in memory. For NJOY, this might be the string path 
            to the output tape file on disk.
        """
        pass

    @abstractmethod
    def cleanup(self, runner_output: Any) -> None:
        """Safely removes any temporary disk files generated during execution.

        Parameters
        ----------
        runner_output : Any
            Backend state returned by the runner for a single evaluation.
        """
        pass


class BaseParser(ABC):
    """
    Abstract interface for extracting physical data from runner outputs.
    
    A Parser is strictly responsible for reading the opaque output produced by 
    the Runner and translating it into the standardized PhysicsData schema.
    """

    @abstractmethod
    def parse(self, sample_index: int, runner_output: Any, **kwargs) -> PhysicsData:
        """
        Extracts results into the unified schema.

        Parameters
        ----------
        sample_index : int
            The unique identifier for the sample.
        runner_output : Any
            The opaque output generated by the BaseRunner.

        Returns
        -------
        PhysicsData
            The rigorously structured physical evaluation containing thermodynamics, 
            differential data, and integral data.
        """
        pass
